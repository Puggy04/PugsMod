#!/usr/bin/env python3
"""Prepare photos as Couch TV wallpapers.

Resizes every photo in the given folders/files to fit 1920x1080 (TV-friendly,
small files), fixes phone rotation, saves them as JPEGs in couch-tv/wallpapers/,
and rewrites js/wallpapers.js so the launcher picks them up.

    pip install pillow pillow-heif        # pillow-heif only needed for iPhone .HEIC photos
    python3 tools/add-wallpapers.py ~/Pictures/TV
    python3 tools/add-wallpapers.py --clear ~/Pictures/TV   # replace instead of add

Then reinstall the app on the TV (see README).
"""
import argparse
import hashlib
import json
import pathlib
import sys

try:
    from PIL import Image, ImageOps
except ImportError:
    sys.exit("Needs Pillow:  pip install pillow pillow-heif")

try:
    import pillow_heif  # type: ignore
    pillow_heif.register_heif_opener()
except ImportError:
    pillow_heif = None

APP = pathlib.Path(__file__).resolve().parent.parent
OUT = APP / "wallpapers"
LIST = APP / "js" / "wallpapers.js"
EXTS = {".jpg", ".jpeg", ".png", ".webp", ".heic", ".heif"}
MAX = (1920, 1080)


def find_images(paths):
    for p in map(pathlib.Path, paths):
        p = p.expanduser()
        if p.is_dir():
            yield from sorted(f for f in p.rglob("*") if f.suffix.lower() in EXTS)
        elif p.suffix.lower() in EXTS:
            yield p


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("paths", nargs="+", help="photo files or folders")
    ap.add_argument("--clear", action="store_true", help="remove existing wallpapers first")
    ap.add_argument("--portrait", action="store_true", help="also include portrait photos (they get cropped)")
    args = ap.parse_args()

    OUT.mkdir(exist_ok=True)
    if args.clear:
        for f in OUT.glob("*.jpg"):
            f.unlink()

    added = skipped = 0
    for src in find_images(args.paths):
        if src.suffix.lower() in {".heic", ".heif"} and pillow_heif is None:
            print(f"skip {src.name}: install pillow-heif for HEIC")
            skipped += 1
            continue
        try:
            im = ImageOps.exif_transpose(Image.open(src)).convert("RGB")
        except Exception as e:  # noqa: BLE001
            print(f"skip {src.name}: {e}")
            skipped += 1
            continue
        if im.height > im.width and not args.portrait:
            print(f"skip {src.name}: portrait (use --portrait to include)")
            skipped += 1
            continue
        # Fill 16:9 so there are no black bars, then shrink to 1080p.
        im = ImageOps.fit(im, MAX, Image.LANCZOS)
        name = hashlib.sha1(src.read_bytes()).hexdigest()[:12] + ".jpg"
        im.save(OUT / name, "JPEG", quality=85, optimize=True, progressive=True)
        added += 1

    files = sorted("wallpapers/" + f.name for f in OUT.glob("*.jpg"))
    LIST.write_text(
        "// Generated by tools/add-wallpapers.py — re-run it after adding photos.\n"
        "window.COUCH_WALLPAPERS = " + json.dumps(files, indent=2) + ";\n"
    )
    print(f"{added} added, {skipped} skipped, {len(files)} wallpapers total → {LIST.relative_to(APP)}")


if __name__ == "__main__":
    main()
